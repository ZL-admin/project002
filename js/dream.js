function searchDreams(keyword, category) {
  let results = DREAM_DICT;
  if (category && category !== '全部') {
    results = results.filter(d => d.cat === category);
  }
  if (keyword) {
    const kw = keyword.trim().toLowerCase();
    results = results.filter(d =>
      d.kw.includes(kw) || d.meaning.includes(kw) || d.detail.includes(kw)
    );
  }
  return results;
}
